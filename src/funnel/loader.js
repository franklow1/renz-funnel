    /* size the closet grid to whatever box it actually has, right now */
    function sizeGrid(gw,gr,n,forceCols,ar){
      var cs=getComputedStyle(gw);
      var W=gw.clientWidth -parseFloat(cs.paddingLeft)-parseFloat(cs.paddingRight),
          H=gw.clientHeight-parseFloat(cs.paddingTop) -parseFloat(cs.paddingBottom);
      if(!W || !H || W<1 || H<1) return false;
      ar=ar||0.72;                                  /* a garment stands up. a day is square. */
      var MIN=9, best=null, c, L, rem, sc2;
      function lay(c){
        var g=c<=8?8:(c<=11?6:5), r=Math.ceil(n/c);
        var w=Math.floor((W-(c-1)*g)/c), h=Math.floor((H-(r-1)*g)/r);
        if(w<1||h<1) return null;
        if(w/h>ar) w=Math.floor(h*ar); else h=Math.floor(w/ar);
        return {c:c,r:r,g:g,w:w,h:h,gw:c*w+(c-1)*g,gh:r*h+(r-1)*g};
      }
      if(forceCols){ best=lay(forceCols);
        /* a calendar keeps its seven columns. when height binds, let the days widen
           rather than leave half the width empty. */
        if(best){ var mw=Math.floor((W-(forceCols-1)*best.g)/forceCols);
          if(best.w<mw) best.w=Math.min(mw,Math.round(best.h*1.45)); } }
      else {
        for(c=Math.min(3,n);c<=Math.min(24,n);c++){
          L=lay(c); if(!L || L.gw>W || L.gh>H) continue;
          rem=(n%c===0)?c:(n%c);
          sc2=Math.min(L.w,L.h)*100-(c-rem)*1.5;    /* biggest cell wins. a ragged last row is a nudge. */
          if(!best||sc2>best.s){ best=L; best.s=sc2; }
        }
        if(!best) best=lay(Math.min(12,n)) || lay(6);
      }
      if(!best) return false;
      var cols=best.c, cg=best.g, rows=Math.ceil(n/cols);
      var cw=Math.max(MIN,best.w), ch=Math.max(MIN,best.h);
      cw=Math.min(cw,Math.max(1,Math.floor((W-(cols-1)*cg)/cols)));   /* MIN must never overflow */
      gr.classList.toggle('tiny',cw<26);
      gr.style.setProperty('--cols',cols);
      gr.style.setProperty('--cw',cw+'px');
      gr.style.setProperty('--ch',ch+'px');
      gr.style.setProperty('--cg',cg+'px');
      gr.style.setProperty('--rad',Math.max(2,Math.round(Math.min(cw,ch)*0.24))+'px');
      gr.style.setProperty('--dn',Math.max(9,Math.round(Math.min(cw,ch)*0.34))+'px');
      var gh=rows*ch+(rows-1)*cg;
      gr.style.transform = gh>H ? 'scale('+(H/gh).toFixed(4)+')' : '';
      return true;
    }

