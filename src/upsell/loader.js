  var HOST_ID   = 'rz-host';
  var HOST_ROOT = '__nuxt';    /* the element their app mounts on */
  var SETTLE    = 700;         /* a page with no checkout on it still gets a moment */
  var LIMIT     = 12000;       /* never leave the funnel floating over their page for good */
  /* Moving the sheet into the page while the host is still building its checkout is what
     emptied the order form and left it at zero pounds with no card field. On a page that
     has a checkout the wait is long, because there is nothing to lose by waiting: the man
     can already see and use the funnel while it floats. The measured time for the checkout
     to come alive is two to four seconds, so thirty is a lot of room for a bad line. */
  var ORDER_LIMIT = 30000;

  function hostRoot(){ return document.getElementById(HOST_ROOT); }
  function mountDiv(){ return document.getElementById(MOUNT_ID); }

  /* their app is up AND the piece of it that we can break is finished */
  var appSeen = 0;
  function hostReady(){
    var r = hostRoot();
    if (!r) return true;
    if (!r.__vue_app__) return false;
    if (!appSeen) appSeen = Date.now();
    var order = document.querySelector('.c-order, [id^="one-step-order-"]');
    if (order) return !!document.querySelector(
      '.payment-content section, iframe[src*="stripe"], .form-btn');
    return Date.now() - appSeen > SETTLE;
  }

  function sheet(){
    if (document.getElementById('rz-host-css')) return;
    var st = document.createElement('style');
    st.id = 'rz-host-css';
    st.appendChild(document.createTextNode(
      '#' + HOST_ID + '.rz-float{position:fixed;top:0;right:0;bottom:0;left:0;' +
      'z-index:2147483000;overflow-y:auto;-webkit-overflow-scrolling:touch;' +
      'background:#F4F1EA}'));
    (document.head || document.documentElement).appendChild(st);
  }

  /* The host page paints its own content, and its order form, in the second before this
     file has even finished downloading. A man saw a checkout he had not asked for, and a
     white page, and could scroll away from a quiz that had not arrived yet.

     So the paste snippet carries an opaque sheet of paper as inline CSS, which the browser
     honours on the first paint. This takes it away the moment there is a funnel underneath
     it instead. If this file never arrives, the sheet stays, which is the right failure:
     a blank page beats somebody's half drawn checkout. */
  function unveil(){
    try{
      var v = document.getElementById('rz-veil');
      if (v && v.parentNode) v.parentNode.removeChild(v);
      var vs = document.getElementById('rz-veil-css');
      if (vs && vs.parentNode) vs.parentNode.removeChild(vs);
    }catch(e){}
  }

  function paint(){
    try{
      var st = document.createElement('style');
      st.setAttribute('data-rz-funnel','1');
      st.appendChild(document.createTextNode(CSS));
      (document.head || document.documentElement).appendChild(st);
      sheet();
      var host = document.getElementById(HOST_ID);
      if (!host){
        host = document.createElement('div');
        host.id = HOST_ID;
      }
      if (hostRoot() && mountDiv()){
        /* their page: start over it, and go into the flow when it is safe */
        (document.body || document.documentElement).appendChild(host);
        host.className = 'rz-float';
      } else if (!host.parentNode){
        /* a bare page: where the tag sits, or failing that the end of the body */
        var m = mountDiv();
        if (m) m.appendChild(host);
        else {
          var sc = document.currentScript;
          if (sc && sc.parentNode) sc.parentNode.insertBefore(host, sc.nextSibling);
          else (document.body || document.documentElement).appendChild(host);
        }
      }
      host.innerHTML = HTML;
    }catch(e){
      if (window.console && console.error) console.error('[RZ] could not paint the funnel', e);
      return false;
    }
    return true;
  }

  /* lift the sheet into the page, keeping his place in it */
  function home(){
    var m = mountDiv(), h = document.getElementById(HOST_ID);
    /* Nothing to move is still settled. Returning quietly here once left anything waiting
       on the handover sat there until the fifteen second fallback fired. */
    if (!m || !h || h.parentNode === m) { settled(); return; }
    var inner = 0;
    try{ inner = h.scrollTop || 0; }catch(e){}
    m.appendChild(h);
    h.className = '';
    try{
      if (inner > 0){
        var top = Math.round(h.getBoundingClientRect().top + window.pageYOffset);
        window.scrollTo(0, top + inner);
      }
    }catch(e){}
    /* the quiz measures the room it has, and it has just been given a different one */
    try{ if (window.RZ && RZ.fitQuiz) RZ.fitQuiz(); }catch(e){}
    settled();
  }

  /* Moving this subtree re-parents everything in it, and a video player that has already
     wired itself to a node loses that node and refuses to start. Wistia says so out loud:
     "Could not find element in DOM. Failed to initialize video." So nothing that embeds
     anything is built until the funnel has stopped moving. */
  function settled(){
    if (window.__rzSettled) return;
    window.__rzSettled = true;
    try{ window.dispatchEvent(new Event('rz:settled')); }catch(e){}
  }
  window.__rzWhenSettled = function(fn){
    if (window.__rzSettled) { try{ fn(); }catch(e){} return; }
    var done = false;
    function go(){ if (done) return; done = true; try{ fn(); }catch(e){} }
    window.addEventListener('rz:settled', go, {once:true});
    /* a page that never settles still has to show its film */
    setTimeout(function(){ settled(); go(); }, 15000);
  };

  /* Wait for the host's checkout to finish drawing, then take the funnel out of its own
     floating sheet and put it into the page. Anything that wants to happen after that
     hands in a callback. */
  function handover(done){
    if (!hostRoot() || !mountDiv()) { settled(); if (done) done(); return; }
    var t0 = Date.now();
    (function poll(){
      var hasOrder = false;
      try{ hasOrder = !!document.querySelector('.c-order, [id^="one-step-order-"]'); }catch(e){}
      var budget = hasOrder ? ORDER_LIMIT : LIMIT;
      if (hostReady() || Date.now() - t0 > budget) { home(); if (done) done(); return; }
      setTimeout(poll, 40);
    })();
  }
  window.__rzHandover = handover;

