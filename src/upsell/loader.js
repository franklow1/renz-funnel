        try{
          var box = document.createElement('div');
          box.innerHTML = tag;
          var l = box.firstChild;
          if(!l || !l.getAttribute) return '';
          var href = l.getAttribute('href') || '';
          if(href && head.querySelector('link[href="' + href.replace(/"/g,'\\"') + '"]')) return '';
          head.appendChild(l);
        }catch(e){}
